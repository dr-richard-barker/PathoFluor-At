"""Build manuscript/references.bib from Crossref records (BibTeX transform), DOI by DOI.

Only DOIs listed here, each confirmed by scripts/crossref_lookup.py, enter the bibliography.
The citation key is set to <firstauthor><year> so the manuscript does not depend on
Crossref's key format. No e-mail address is sent in request headers.
"""
import re
import unicodedata
import time
import urllib.parse
import urllib.request
from pathlib import Path

UA = "PathoFluor-At/0.1 (https://github.com/dr-richard-barker/PathoFluor-At)"
DOIS = {
    "ishiga2011": "10.1186/1746-4811-7-32",
    "gomezgomez2000": "10.1016/s1097-2765(00)80265-8",
    "gomezgomez1999": "10.1046/j.1365-313x.1999.00451.x",
    "felix1999": "10.1046/j.1365-313x.1999.00265.x",
    "chinchilla2006": "10.1105/tpc.105.036574",
    "zipfel2004": "10.1038/nature02485",
    "delk2005": "10.1104/pp.105.062612",
    "ma2008": "10.1104/pp.108.125104",
    "gohre2012": "10.1094/mpmi-11-11-0301",
    "buschmann2007": "10.1007/s11120-007-9187-8",
    "perezbueno2016": "10.3389/fpls.2016.01790",
    "perezbueno2019": "10.3389/fpls.2019.01135",
    "mahlein2016": "10.1094/pdis-03-15-0340-fe",
    "dejuan2021": "10.1016/j.aca.2020.10.051",
    "bonfig2006": "10.1007/s00425-006-0303-3",
    "rousseau2013": "10.1186/1746-4811-9-17",
    "benjamini1995": "10.1111/j.2517-6161.1995.tb02031.x",
    "papoutsoglou2020": "10.1111/nph.16544",
    "wilkinson2016": "10.1038/sdata.2016.18",
}

# Crossref truncates this title to "FLS2"; full title from PubMed PMID 10911994 (same DOI).
TITLE_FIX = {"gomezgomez2000": "FLS2: an LRR receptor-like kinase involved in the perception of the "
                               "bacterial elicitor flagellin in Arabidopsis"}


def clean(bib, key):
    bib = unicodedata.normalize("NFC", bib)       # composed accents (pdflatex rejects U+0301)
    bib = bib.replace("\u0131\u0301", "\u00ed")   # dotless i + acute (Crossref spelling of Ramírez)
    bib = re.sub(r",\s*month=\w+", "", bib)        # Crossref month names are not BibTeX macros
    bib = re.sub(r"\s+", " ", bib)
    bib = re.sub(r"<i>\s*(.*?)\s*</i>", r"\\textit{\1}", bib)
    bib = re.sub(r"</?(sub|sup|b)>", "", bib)
    for u, a in {"\u2010": "-", "\u2011": "-", "\u2012": "--", "\u2013": "--", "\u2014": "---",
                 "\u00a0": " ", "\u00ae": ""}.items():
        bib = bib.replace(u, a)
    if key in TITLE_FIX:
        bib = re.sub(r"title=\{.*?\}, volume", "title={" + TITLE_FIX[key] + "}, volume", bib, count=1)
    return bib


out = ["% Generated by scripts/make_bib.py from Crossref records. Do not edit by hand.\n"]
for key, doi in DOIS.items():
    url = f"https://api.crossref.org/works/{urllib.parse.quote(doi)}/transform/application/x-bibtex"
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        bib = r.read().decode("utf-8").strip()
    bib = re.sub(r"^@(\w+)\{[^,]*,", lambda m: "@" + m.group(1) + "{" + key + ",", bib, count=1)
    out.append(clean(bib, key) + "\n")
    time.sleep(1)
# Unpublished vendor reports (no DOI; titles and dates as on the documents; FACTS V1, V2, R19).
out.append("@techreport{msv2016july, author={Jones, Howland}, title={Arabidopsis Imaging, UW Arabidopsis "
           "(msv091416)}, institution={Middleton Spectral Vision}, type={Unpublished technical report "
           "(slides)}, year={2016}, note={Analysis of the July 2016 experiment; not publicly available}}\n")
out.append("@techreport{msv2017nov, author={Jones, Howland}, title={Arabidopsis Imaging, UW Arabidopsis, "
           "October Experiment}, institution={Middleton Spectral Vision}, type={Unpublished technical "
           "report}, year={2017}, note={Analysis of the November 2016 replicate; not publicly available}}\n")
Path("manuscript/references.bib").write_text("\n".join(out))
print(f"wrote {len(DOIS)} entries")
