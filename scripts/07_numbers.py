"""Write manuscript/numbers.tex: every number quoted in the manuscript and slides, as a LaTeX
macro computed from the committed tables (ABAI L007: no hard-coded results).
A missing selector raises, so a stale or renamed table cannot silently drop a number.
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from pathofluor.config import META, REPO, RESULTS, TABLES  # noqa: E402

OUT = {}


def put(name, value, fmt="{:.2f}"):
    if value is None or (isinstance(value, float) and not np.isfinite(value)):
        raise SystemExit(f"numbers: {name} is missing")
    OUT[name] = fmt.format(value) if not isinstance(value, str) else value


def one(df, **sel):
    d = df
    for k, v in sel.items():
        d = d[d[k] == v]
    if len(d) != 1:
        raise SystemExit(f"numbers: selector {sel} matched {len(d)} rows")
    return d.iloc[0]


def pfmt(p):
    return f"{p:.3f}" if p >= 0.001 else f"{p:.1e}".replace("e-0", "\\times10^{-") + "}"


def tex_table(df, cols, header, path, caption, label, fmt=None):
    fmt = fmt or {}
    body = []
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            f = fmt.get(c)
            cells.append(f(v) if f else (f"{v:.2f}" if isinstance(v, float) else str(v)))
        body.append(" & ".join(cells).replace("_", "\\_") + " \\\\")
    tex = ["\\begin{table}[ht]\\centering\\small", f"\\caption{{{caption}}}\\label{{{label}}}",
           "\\begin{tabular}{" + "l" * len(cols) + "}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule",
           *body, "\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (REPO / "manuscript" / "generated").mkdir(exist_ok=True)
    (REPO / "manuscript" / "generated" / path).write_text("% Generated by scripts/07_numbers.py\n" + "\n".join(tex) + "\n")


def write_tables():
    D = pd.read_csv(RESULTS / "label_direction_scores.csv")
    D = D[D["set"] == "A"].sort_values(["hour", "treatment", "plate"])
    tex_table(D, ["hour", "treatment", "plate", "n_roi", "n_seedlings", "score_fwd", "score_rev", "direction"],
              ["Hour", "Treatment", "Plate", "ROIs", "Seedlings", "Score fwd", "Score rev", "Chosen"],
              "tab_label_direction.tex",
              "Scan direction per set-A plate and timepoint, chosen by agreement between the 2016 hand ROIs "
              "and the seedlings each direction assigns to them (mean within-plate Spearman correlation of "
              "three features). Source: results/label\\_direction\\_scores.csv.", "tab:labels",
              fmt={"hour": lambda v: f"{v:g}", "plate": lambda v: f"{v:g}", "n_roi": lambda v: f"{int(v)}",
                   "n_seedlings": lambda v: f"{int(v)}", "direction": lambda v: str(v) if isinstance(v, str) else "--"})
    B = pd.read_csv(TABLES / "stats_contrasts_baseline_adjusted.csv")
    B = B[(B["set"] == "A") & (B.p < 0.01)].sort_values("p")
    tex_table(B, ["hour", "feature", "contrast", "effect_sd", "effect_raw", "p", "q"],
              ["Hour", "Feature", "Contrast", "Effect (SD)", "Effect (units)", "$p$", "$q$"],
              "tab_baseline_top.tex",
              "Baseline-adjusted contrasts with $p<0.01$ (set A; all 270 tests in "
              "tables/stats\\_contrasts\\_baseline\\_adjusted.csv).", "tab:baseline",
              fmt={"hour": lambda v: f"{v:g}", "effect_raw": lambda v: f"{v:.4g}", "p": lambda v: f"{v:.1e}",
                   "q": lambda v: f"{v:.3f}"})


def main():
    inv = pd.read_csv(META / "file_inventory.csv")
    cm = pd.read_csv(META / "cube_manifest.csv")
    rm = pd.read_csv(META / "roi_manifest.csv")
    put("nFiles", len(inv), "{:,}")
    put("nCubes", int(cm["set"].isin(["A", "B"]).sum()), "{:,}")
    put("nCubesA", int(((cm["set"] == "A") & (cm.role == "sample")).sum()), "{:,}")
    put("nCubesB", int(((cm["set"] == "B") & (cm.role == "sample")).sum()), "{:,}")
    put("nRoiFiles", int(rm["set"].isin(["A", "B"]).sum()), "{:,}")
    put("nRoiUnique", int(rm[rm["set"].isin(["A", "B"])].spectrum_id.nunique()), "{:,}")
    put("nRoiA", int(rm[rm["set"] == "A"].spectrum_id.nunique()), "{:,}")
    put("nRoiB", int(rm[rm["set"] == "B"].spectrum_id.nunique()), "{:,}")
    put("rawGB", inv[inv.category.isin(["set_A", "set_B"])].bytes.sum() / 1e9, "{:.0f}")

    e = pd.read_csv(TABLES / "fig1_exposure_artefact.csv").set_index("hour")
    put("rawFzero", e.loc[0, "raw"], "{:,.0f}")
    put("rawFone", e.loc[1, "raw"], "{:,.0f}")
    put("rawDropPct", 100 * (1 - e.loc[1, "raw"] / e.loc[0, "raw"]), "{:.0f}")
    put("cpsDiffPct", 100 * abs(e.loc[[1, 2, 3], "cps"].mean() / e.loc[0, "cps"] - 1), "{:.0f}")

    qc = [json.loads(p.read_text()) for p in (RESULTS / "cube_qc").glob("A_H00_*.json")]
    if qc:
        sat = np.array([q["n_saturated_fg_pixels"] for q in qc]) / np.array([q["n_fg_pixels"] for q in qc])
        put("satHzeroMaxPct", 100 * sat.max(), "{:.0f}")
        put("satHzeroMedPct", 100 * np.median(sat), "{:.1f}")

    B = pd.read_csv(TABLES / "stats_contrasts_baseline_adjusted.csv")
    for hr, tag in ((1, "One"), (2, "Two")):
        r = one(B, set="A", hour=hr, feature="red_fwhm_nm", contrast="Pathogen vs Control (Col-0)")
        put(f"pathFwhm{tag}SD", r.effect_sd)
        put(f"pathFwhm{tag}nm", r.effect_raw)
        put(f"pathFwhm{tag}q", pfmt(r.q), "{}")
    r = one(B, set="A", hour=2, feature="shortwave_fraction", contrast="Pathogen vs Control (Col-0)")
    put("pathSwTwoSD", r.effect_sd)
    put("pathSwTwoq", pfmt(r.q), "{}")
    for hr, tag in ((3, "Three"), (24, "TwentyFour")):
        r = one(B, set="A", hour=hr, feature="red_fwhm_nm", contrast="Pathogen vs Control (Col-0)")
        put(f"pathFwhm{tag}nm", r.effect_raw)
        put(f"pathFwhm{tag}q", pfmt(r.q), "{}")
        r = one(B, set="A", hour=hr, feature="shortwave_fraction", contrast="Pathogen vs Control (Col-0)")
        put(f"pathSw{tag}SD", r.effect_sd)
        put(f"pathSw{tag}q", pfmt(r.q), "{}")
    r = one(B, set="A", hour=24, feature="shortwave_fraction", contrast="Pathogen x cml24-4")
    put("cmlFourSwSD", r.effect_sd)
    put("cmlFourSwq", pfmt(r.q), "{}")
    r = one(B, set="A", hour=3, feature="red_fwhm_nm", contrast="flg22 vs Control (Col-0)")
    put("flgFwhmThreeSD", r.effect_sd)
    put("flgFwhmThreeq", pfmt(r.q), "{}")
    put("nBaselineTests", int((B["set"] == "A").sum()), "{:,}")
    put("nBaselineSig", int(((B["set"] == "A") & (B.q < 0.05)).sum()), "{:d}")

    C = pd.read_csv(TABLES / "stats_contrasts.csv")
    r = one(C, set="A", hour=0, feature="red_fwhm_nm", contrast="flg22 vs Control (Col-0)")
    put("hzeroFlgFwhmSD", r.effect_sd)
    put("hzeroFlgFwhmq", pfmt(r.q), "{}")
    r = one(C, set="B", hour=6, feature="f685_f740", contrast="flg22 x fls2-17")
    put("setBinterSD", r.effect_sd)
    put("setBinterq", pfmt(r.q), "{}")
    put("setBinterN", int(((C["set"] == "B") & (C.hour == 6) & (C.q < 0.05)).sum()), "{:d}")

    A = pd.read_csv(TABLES / "model_auc.csv")
    sel = dict(genotypes="Col-0", model="logistic", features="spectrum")
    for hr, tag in ((1, "One"), (2, "Two"), (24, "TwentyFour")):
        r = one(A, variant="baseline-relative", hour=hr, contrast="Pathogen vs Control", **sel)
        put(f"aucPath{tag}", r.auc_plate)
        put(f"pPath{tag}", r.perm_p_plate, "{:.3f}")
    r = one(A, variant="baseline-relative", hour=3, contrast="Pathogen vs Control", **sel)
    put("aucPathThree", r.auc_plate)
    put("pPathThree", r.perm_p_plate, "{:.3f}")
    r = one(A, variant="absolute", hour=0, contrast="flg22 vs Control", **sel)
    put("aucPlaceboFlg", r.auc_plate)
    put("pPlaceboFlg", r.perm_p_plate, "{:.3f}")
    r = one(A, variant="absolute", hour=0, contrast="Pathogen vs Control", **sel)
    put("aucPlaceboPath", r.auc_plate)
    fl = A[(A.variant == "baseline-relative") & (A.contrast == "flg22 vs Control") & (A.hour.isin([1, 2, 3]))
           & (A.genotypes == "Col-0") & (A.model == "logistic") & (A.features == "spectrum")]
    put("aucFlgEarlyMin", fl.auc_plate.min())
    put("aucFlgEarlyMax", fl.auc_plate.max())
    put("pFlgEarlyMin", fl.perm_p_plate.min(), "{:.2f}")
    put("nPermFlgBase", int(fl.n_perm.iloc[0]), "{:d}")

    S = pd.read_csv(TABLES / "model_specificity.csv")
    s = S[(S.variant == "baseline-relative") & (S.contrast == "flg22 vs Control") & (S.hour.isin([1, 2, 3]))]
    piv = s.groupby("genotype").delta_p.mean()
    put("specFlgColO", piv["Col-0"])
    put("specFlgFlsSeventeen", piv["fls2-17"])
    put("specFlgFlsOneOhOne", piv["fls2-101"])

    # ---- seedling-level (raw cubes)
    SS = pd.read_csv(TABLES / "seedling_stats.csv")
    SA = SS[SS["set"] == "A"]
    for hr, f, tag in ((1, "red_fwhm_nm", "SeedFwhmOne"), (1, "f685_f740", "SeedRatioOne"),
                       (3, "f685_cps", "SeedCpsThree"), (48, "f685_cps", "SeedCpsFortyEight"),
                       (48, "shortwave_fraction", "SeedSwFortyEight"), (48, "n_px", "SeedAreaFortyEight"),
                       (48, "ratio_px_sd", "SeedHetFortyEight"), (2, "mcr2_frac", "SeedMcrTwoTwo")):
        r = one(SA, hour=hr, feature=f, contrast="Pathogen vs Control")
        put(f"path{tag}", r.delta, "{:,.0f}" if "cps" in f or f == "n_px" else "{:.2f}" if abs(r.delta) >= 0.1 else "{:.3f}")
        put(f"path{tag}q", pfmt(r.q), "{}")
    put("nSeedA", int(pd.read_csv(RESULTS / "seedlings_labelled.csv.gz").query("set == 'A'").shape[0]), "{:,}")
    put("nSeedSigA", int(((SA.q < 0.05)).sum()), "{:d}")
    GS = pd.read_csv(TABLES / "seedling_genotype_stats.csv")
    put("nGenoSigA", int(((GS["set"] == "A") & (GS.q < 0.1)).sum()), "{:d}")
    for g, tag in (("fls2-17", "Seventeen"), ("fls2-101", "OneOhOne")):
        r = one(GS, set="B", laser=58.0, hour=48.0, feature="shortwave_px_p90", contrast=f"flg22 x {g}")
        put(f"setBflsHet{tag}SD", r.effect_sd)
        put(f"setBflsHet{tag}q", pfmt(r.q), "{}")
    put("nSetBPlateSig", int(((SS["set"] == "B") & (SS.q < 0.1)).sum()), "{:d}")
    pc = pd.read_csv(TABLES / "seedling_plate_changes.csv")
    r = one(pc, set="B", laser=58, hour=48.0, treatment="Control", plate=2.0)
    put("setBctrlTwoSw", r.shortwave_fraction)
    comp = pd.read_csv(RESULTS / "mcr_components.csv")
    w = comp.wl
    fr = [comp[c][(w >= 500) & (w <= 640)].sum() / comp[c].sum() for c in comp.columns if c.startswith("comp")]
    put("mcrMaxSwPct", 100 * max(fr), "{:.1f}")
    pk = sorted(float(w[comp[c].idxmax()]) for c in comp.columns if c.startswith("comp"))
    put("mcrPeakLo", pk[0], "{:.0f}")
    put("mcrPeakHi", pk[-1], "{:.0f}")
    bc = pd.read_csv(TABLES / "setb_control_scans.csv")
    bb = bc[bc.role == "bacteria_scan"]
    put("bactMaxSigPct", 100 * bb.signal_fraction.max(), "{:.2f}")
    put("bactMaxSwCps", bb.sw_cps.max(), "{:.1f}")
    LB = pd.read_csv(RESULTS / "label_direction_setB.csv")
    put("setBdirWins", int((LB.score_fwd > LB.score_rev).sum()), "{:d}")
    put("setBdirN", len(LB), "{:d}")
    LD = pd.read_csv(RESULTS / "label_direction_scores.csv")
    LD = LD[LD["set"] == "A"]
    put("labPlates", int(LD.direction.notna().sum()), "{:d}")
    put("labPlatesAll", len(LD), "{:d}")
    put("labLowConf", int((LD.margin < 0.2).sum()), "{:d}")
    put("nShaRaw", int(cm.sha256_raw.notna().sum()), "{:d}")

    write_tables()
    rm_a = rm[rm["set"] == "A"]
    put("nUseSubset", int(rm_a[rm_a.location == "use_subset"].spectrum_id.nunique()), "{:,}")
    put("nCopyFiles", int(rm_a.file_copy.fillna(False).astype(bool).sum()), "{:d}")
    F = pd.read_csv(RESULTS / "roi_features.csv.gz")
    put("nOffsetRoi", int(F.offset_corrected.sum()), "{:d}")
    put("offsetMedian", F.loc[F.offset_corrected, "dark_residual"].median(), "{:.0f}")
    put("offsetCleanMedian", F.loc[~F.offset_corrected & (F["set"] == "A"), "dark_residual"].median(), "{:.1f}")
    put("nKeyConflict", int(F.key_conflict.sum()), "{:d}")
    put("nTagValues", int(F[F["set"] == "A"].tag.nunique()), "{:d}")

    lines = ["% Generated by scripts/07_numbers.py from tables/ and metadata/. Do not edit by hand."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in OUT.items()]
    (REPO / "manuscript" / "numbers.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
